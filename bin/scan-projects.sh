#!/usr/bin/env bash
# Give every repository a pinned colour and icon in the hq sidebar.
#
#   ./bin/scan-projects.sh                  discover roots automatically
#   ./bin/scan-projects.sh ~/code ~/work    scan these roots
#   ./bin/scan-projects.sh --dry-run ~/code print the generated block only
#
# Colours and icons already work without this — every repo gets a stable colour
# derived from its name. This only pins specific ones.
set -euo pipefail

DRY=0
ROOTS=()
for a in "$@"; do
  case "$a" in
    --dry-run) DRY=1 ;;
    *) ROOTS+=("$a") ;;
  esac
done

# 1. explicit args  2. directories cmux already has open  3. common roots
if [ "${#ROOTS[@]}" -eq 0 ] && command -v cmux >/dev/null 2>&1; then
  while IFS= read -r d; do
    [ -n "$d" ] && ROOTS+=("$(dirname "$d")")
  done < <(cmux workspace list --json 2>/dev/null \
           | python3 -c 'import json,sys
try:
    for w in json.load(sys.stdin).get("workspaces", []):
        d = w.get("current_directory")
        if d: print(d)
except Exception: pass' || true)
fi

if [ "${#ROOTS[@]}" -eq 0 ]; then
  for c in "$HOME/code" "$HOME/src" "$HOME/dev" "$HOME/repos" "$HOME/Developer" \
           "$HOME/work" "$HOME/git" "$HOME/Projects" "$HOME/Documents/GitHub"; do
    [ -d "$c" ] && ROOTS+=("$c")
  done
fi

if [ "${#ROOTS[@]}" -eq 0 ]; then
  echo "No project roots found. Pass one explicitly: $0 ~/path/to/code" >&2
  exit 1
fi

# de-duplicate roots (bash 3.2 compatible)
DEDUP=()
while IFS= read -r r; do [ -n "$r" ] && DEDUP+=("$r"); done < <(printf '%s\n' "${ROOTS[@]}" | sort -u)
ROOTS=("${DEDUP[@]}")
echo "Scanning: ${ROOTS[*]}" >&2

REPOS=()
for root in "${ROOTS[@]}"; do
  while IFS= read -r g; do
    REPOS+=("$(dirname "$g")")
  done < <(find "$root" -mindepth 2 -maxdepth 3 -name .git 2>/dev/null | head -200)
done
DEDUP=()
while IFS= read -r r; do [ -n "$r" ] && DEDUP+=("$r"); done < <(printf '%s\n' "${REPOS[@]}" | sort -u)
REPOS=("${DEDUP[@]}")

if [ "${#REPOS[@]}" -eq 0 ]; then
  echo "No git repositories found under those roots." >&2
  exit 1
fi
echo "Found ${#REPOS[@]} repositories." >&2

BLOCK=$(python3 - "${REPOS[@]}" <<'PY'
import json, os, sys

palette = ["#FF7A45", "#7FD98A", "#4FC3D9", "#C79BF0", "#F2C55C",
           "#7FB4FF", "#FF8A8A", "#6FDCB4", "#D4A574", "#E88FC0"]

def icon_for(path):
    has = lambda *names: any(os.path.exists(os.path.join(path, n)) for n in names)
    pkg = os.path.join(path, "package.json")
    if os.path.exists(pkg):
        try:
            deps = json.load(open(pkg))
            blob = json.dumps({**deps.get("dependencies", {}), **deps.get("devDependencies", {})}).lower()
        except Exception:
            blob = ""
        if "phaser" in blob or "three" in blob: return "gamecontroller.fill"
        if "next" in blob or "react" in blob or "vue" in blob or "svelte" in blob: return "globe"
        if "electron" in blob: return "macwindow"
        return "chevron.left.forwardslash.chevron.right"
    if has("go.mod"): return "shippingbox.fill"
    if has("Cargo.toml"): return "gearshape.2.fill"
    if has("pyproject.toml", "requirements.txt", "setup.py"): return "chart.line.uptrend.xyaxis"
    if has("Package.swift"): return "swift"
    if has("main.tf", "terraform.tf"): return "cloud.fill"
    if has("Dockerfile", "compose.yaml", "docker-compose.yml"): return "cube.box.fill"
    if has("mkdocs.yml", "docusaurus.config.js") or os.path.exists(os.path.join(path, "docs")): return "book.fill"
    return "folder.fill"

repos = sorted(set(sys.argv[1:]), key=lambda p: os.path.basename(p).lower())
colors, icons = [], []
for i, p in enumerate(repos):
    name = os.path.basename(p)
    colors.append(f'    if dir.contains("{name}") {{ return "{palette[i % len(palette)]}" }}')
    icons.append(f'    if dir.contains("{name}") {{ return "{icon_for(p)}" }}')

print("// >>> project overrides — generated by bin/scan-projects.sh, safe to hand-edit")
print("func colorOverride(_ dir: String) -> String {")
print("\n".join(colors))
print('    return ""')
print("}")
print()
print("func iconOverride(_ dir: String) -> String {")
print("\n".join(icons))
print('    return ""')
print("}")
print("// <<< project overrides")
PY
)

if [ "$DRY" = 1 ]; then
  printf '%s\n' "$BLOCK"
  exit 0
fi

TARGET="$HOME/.config/cmux/sidebars/hq.swift"
[ -f "$TARGET" ] || { echo "Not installed yet: $TARGET" >&2; exit 1; }

cp "$TARGET" "$TARGET.$(date +%Y%m%d%H%M%S).bak"
BLOCK="$BLOCK" python3 - "$TARGET" <<'PY'
import os, re, sys
p = sys.argv[1]
s = open(p).read()
new = os.environ["BLOCK"]
start = s.index("// >>> project overrides")
end = s.index("// <<< project overrides") + len("// <<< project overrides")
open(p, "w").write(s[:start] + new + s[end:])
PY
echo "Updated $TARGET" >&2
command -v cmux >/dev/null 2>&1 && cmux sidebar validate hq >&2 || true
